/// A single activity in the smart home catalog.
/// `recapModule` is set only for the five spaced-repetition modules so the
/// home grid can surface their pending review counts.
class Activity {
  const Activity({
    required this.id,
    required this.titleEn,
    required this.titleAr,
    required this.subtitleEn,
    required this.subtitleAr,
    required this.emoji,
    required this.accent,
    required this.route,
    required this.category,
    this.recapModule,
    this.featured = false,
  });

  final String id;
  final String titleEn;
  final String titleAr;
  final String subtitleEn;
  final String subtitleAr;
  final String emoji;
  final Color accent;
  final String route;
  final ActivityCategory category;
  final RecapModule? recapModule;
  final bool featured;

  String title({required bool ar}) => ar ? titleAr : titleEn;
  String subtitle({required bool ar}) => ar ? subtitleAr : subtitleEn;

  bool matches(String query) {
    if (query.isEmpty) return true;
    final q = query.toLowerCase().trim();
    return titleEn.toLowerCase().contains(q) ||
        subtitleEn.toLowerCase().contains(q) ||
        titleAr.contains(q) ||
        subtitleAr.contains(q);
  }
}

