List<Activity> activitiesByCategory(ActivityCategory category) =>
    kActivities.where((a) => a.category == category).toList();

List<Activity> filterActivities({
  ActivityCategory? category,
  String query = '',
}) {
  Iterable<Activity> base = kActivities;
  if (category != null) {
    base = base.where((a) => a.category == category);
  }
  if (query.isNotEmpty) {
    base = base.where((a) => a.matches(query));
  }
  return base.toList();
}

Activity? activityById(String id) {
  for (final a in kActivities) {
    if (a.id == id) return a;
  }
  return null;
}
